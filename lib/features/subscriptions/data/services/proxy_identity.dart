import 'dart:convert';

import '../../../converter/domain/entities/parsed_proxy.dart';

/// Connection identity includes credentials and transport options, but excludes
/// the display name. Two accounts on the same host/port are separate profiles.
String proxyIdentity(ParsedProxy proxy) => jsonEncode([
  proxy.runtimeType.toString(),
  proxy.host.toLowerCase(),
  proxy.port,
  switch (proxy) {
    VlessConfig p => [
      p.uuid,
      p.flow,
      p.encryption,
      p.security,
      p.sni,
      p.fingerprint,
      p.publicKey,
      p.shortId,
      p.spiderX,
      p.transport,
      p.path,
      p.transportHost,
      p.grpcServiceName,
      p.xhttpMode,
      p.xPaddingBytes,
      p.alpn,
      p.allowInsecure,
    ],
    VmessConfig p => [
      p.uuid,
      p.alterId,
      p.security,
      p.network,
      p.path,
      p.wsHost,
      p.tls,
      p.sni,
      p.alpn,
      p.fingerprint,
    ],
    TrojanConfig p => [
      p.password,
      p.security,
      p.sni,
      p.alpn,
      p.fingerprint,
      p.transport,
      p.path,
      p.transportHost,
    ],
    ShadowsocksConfig p => [p.method, p.password, p.plugin, p.pluginOpts],
    Hysteria2Config p => [
      p.auth,
      p.sni,
      p.insecure,
      p.obfs,
      p.obfsPassword,
      p.pinSha256,
      p.ports,
      p.hopInterval,
    ],
    TuicConfig p => [
      p.uuid,
      p.password,
      p.sni,
      p.alpn,
      p.congestionControl,
      p.udpRelayMode,
      p.allowInsecure,
    ],
    WireGuardConfig p => [
      p.privateKey,
      p.publicKey,
      p.presharedKey,
      p.addresses,
      p.dns,
      p.mtu,
      p.reserved,
    ],
    AmneziaWGConfig p => [
      p.privateKey,
      p.publicKey,
      p.presharedKey,
      p.addresses,
      p.dns,
      p.mtu,
      p.reserved,
      p.jc,
      p.jmin,
      p.jmax,
      p.s1,
      p.s2,
      p.s3,
      p.s4,
      p.h1,
      p.h2,
      p.h3,
      p.h4,
    ],
    NaiveConfig p => [p.username, p.password, p.scheme],
    ShadowTlsConfig p => [
      p.password,
      p.sni,
      p.version,
      proxyIdentity(p.innerProxy),
    ],
  },
]);
